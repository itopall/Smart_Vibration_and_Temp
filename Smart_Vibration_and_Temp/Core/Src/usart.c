HAL_StatusTypeDef UART_SendString(UART_Config_t *config, char *data)
{
	 if (data == NULL) return HAL_ERROR;


	uint16_t len = strlen(data);

	return HAL_UART_Transmit(config->huart, (uint8_t*)data, len, config->timeout);
}

HAL_StatusTypeDef UART_ReceiveString(UART_Config_t *config, char *buffer, uint16_t buffer_size)
{
    memset(buffer, 0, buffer_size);
    return HAL_UART_Receive(config->huart, (uint8_t*)buffer, buffer_size - 1, config->timeout);
}

HAL_StatusTypeDef UART_SendString_DMA(UART_Config_t *config, const char *data)
{
    uint16_t len = strlen(data);
    return HAL_UART_Transmit_DMA(config->huart, (uint8_t*)data, len);
}
